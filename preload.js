const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('aurea', {
  platform: process.platform,
  open: () => ipcRenderer.invoke('file:open'),
  openPath: (p) => ipcRenderer.invoke('file:openPath', p),
  save: (o) => ipcRenderer.invoke('file:save', o),
  writeQuiet: (o) => ipcRenderer.invoke('file:writeQuiet', o),
  autosave: (d) => ipcRenderer.invoke('file:autosave', d),
  recovery: () => ipcRenderer.invoke('file:recovery'),
  clearRecovery: () => ipcRenderer.invoke('file:clearRecovery'),
  recent: () => ipcRenderer.invoke('recent:list'),
  removeRecent: (p) => ipcRenderer.invoke('recent:remove', p),
  pickImages: (multi) => ipcRenderer.invoke('image:pick', multi),
  exportHtml: (o) => ipcRenderer.invoke('export:html', o),
  exportPdf: (o) => ipcRenderer.invoke('export:pdf', o),
  fullscreen: (on) => ipcRenderer.invoke('win:fullscreen', on),
  showItem: (p) => ipcRenderer.invoke('shell:show', p),
  argFile: () => ipcRenderer.invoke('app:argFile'),
  displays: () => ipcRenderer.invoke('app:displays'),
  openAudience: () => ipcRenderer.invoke('show:audience'),
  closeAudience: () => ipcRenderer.invoke('show:closeAudience'),
  openHtml: () => ipcRenderer.invoke('html:open'),
  openHtmlPath: (p) => ipcRenderer.invoke('html:openPath', p),
  closeHtml: () => ipcRenderer.invoke('html:close'),
  htmlFullscreen: (on) => ipcRenderer.invoke('html:fullscreen', on),
  htmlReload: () => ipcRenderer.invoke('html:reload'),
  htmlFocus: () => ipcRenderer.invoke('html:focus'),
  htmlHide: (h) => ipcRenderer.invoke('html:hide', h),
  setAssoc: (on) => ipcRenderer.invoke('assoc:set', on),
  pathForFile: (f) => { try { return webUtils.getPathForFile(f); } catch { return ''; } },
  netJson: (u) => ipcRenderer.invoke('net:json', u),
  netImage: (u) => ipcRenderer.invoke('net:image', u),
  aiImage: (o) => ipcRenderer.invoke('ai:image', o),
  aiOutline: (o) => ipcRenderer.invoke('ai:outline', o),
  openLink: (u) => ipcRenderer.invoke('open:link', u),
  exportPdfRaster: (o) => ipcRenderer.invoke('export:pdfRaster', o),
  histSave: (o) => ipcRenderer.invoke('hist:save', o),
  histList: (k) => ipcRenderer.invoke('hist:list', k),
  histLoad: (o) => ipcRenderer.invoke('hist:load', o),
  aiSettings: (patch) => ipcRenderer.invoke('ai:settings', patch),
  setTheme: (t) => ipcRenderer.invoke('win:theme', t),
  openPinterest: (q) => ipcRenderer.invoke('pin:open', q),
  savePptx: (o) => ipcRenderer.invoke('pptx:save', o),
  openPptx: () => ipcRenderer.invoke('pptx:open'),
  debugWriteB64: (o) => ipcRenderer.invoke('debug:writeB64', o),
  debugWrite: (o) => ipcRenderer.invoke('debug:write', o),
  debugPdf: (o) => ipcRenderer.invoke('debug:pdf', o),
  on: (ch, fn) => ipcRenderer.on(ch, (_e, ...a) => fn(...a))
});
